#!/usr/bin/env python3
"""Generate the compact u8g2 CJK font + bilingual stop table for the NOTE4.

Inputs : ~/macau-bus/data/stops.json  (id, nameEn, nameCn, routes, lat, lng)
Tool   : bdfconv from u8g2 (tools/font/bdfconv) — build once:
             git clone https://github.com/olikraus/u8g2 /tmp/u8g2
             gcc -O2 -o /tmp/bdfconv/bdfconv /tmp/u8g2/tools/font/bdfconv/*.c -lm
BDF    : wenquanyi_9pt.bdf (12px WenQuanYi bitmap song, full GB CJK coverage)
             https://github.com/larryli/u8g2_wqy (bdf/wenquanyi_9pt.bdf)

Outputs (in main/):
  u8g2_font_macau.c/.h  — u8g2-format font with exactly the CJK glyphs used
                          by the stop names (a few KB, vs 900 KB for a
                          full-range 16x16 bitmap).
  bus_stops_data.h      — all stops with English + Chinese names.
"""

import json
import os
import re
import subprocess
import sys

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MAIN = os.path.join(REPO, "main")
STOPS_JSON = os.path.expanduser("~/macau-bus/data/stops.json")
BDF = os.environ.get("WQY_BDF", "/tmp/wqy12.bdf")
BDFCONV = os.environ.get("BDFCONV", "/tmp/bdfconv/bdfconv")
FONT_NAME = "u8g2_font_wqy12_t_macau"


def ranges(chars):
    out = []
    start = 0
    prev = -1
    for c in sorted(chars):
        if prev < 0:
            start = prev = c
        elif c == prev + 1:
            prev = c
        else:
            out.append((start, prev))
            start = prev = c
    if start is not None and prev >= 0:
        out.append((start, prev))
    return out


def main():
    stops = json.load(open(STOPS_JSON))
    charset = set()
    for s in stops:
        charset.update(s.get("nameCn", ""))
        charset.update(s.get("nameEn", ""))
    high = {ord(c) for c in charset if ord(c) > 127}
    print(f"{len(stops)} stops, {len(high)} non-ASCII chars")

    m = "32-$7F," + ",".join(
        ("${:X}-${:X}" if a != b else "${:X}").format(a, b) for a, b in ranges(high))
    out_c = os.path.join(MAIN, "u8g2_font_macau.c")
    subprocess.run(
        [BDFCONV, BDF, "-o", out_c, "-n", FONT_NAME, "-b", "0", "-m", m],
        check=True,
        stdout=subprocess.DEVNULL,
        stderr=subprocess.DEVNULL,
    )

    # Normalize: plain uint8_t array (ucg type name -> uint8_t).
    src = open(out_c).read()
    src = src.replace("const ucg_fntpgm_uint8_t", "const uint8_t")
    src = re.sub(r"\s*UCG_FONT_SECTION\([^)]*\)", "", src)
    src = src.replace('#include "ucg.h"', "#include <stdint.h>")
    open(out_c, "w").write(src)

    m = re.search(r"\[(\d+)\]", src)
    size = int(m.group(1)) if m else 0
    with open(os.path.join(MAIN, "u8g2_font_macau.h"), "w") as f:
        f.write(
            "// Generated by tools/gen_stop_assets.py — do not edit.\n"
            "#pragma once\n#include <stdint.h>\n\n"
            f"extern const uint8_t {FONT_NAME}[{size}];\n")
    print(f"font: {size} bytes")

    with open(os.path.join(MAIN, "bus_stops_data.h"), "w") as f:
        f.write(
            "// Generated by tools/gen_stop_assets.py from macau-bus\n"
            "// data/stops.json — all DSAT stops with English + Chinese names\n"
            "// (UTF-8). Regen with tools/gen_stop_assets.py, don't hand-edit.\n"
            "#pragma once\n\n#include <cstddef>\n#include <cstdint>\n\n"
            "namespace bus_stops {\n\n"
            "struct Stop {\n"
            "    const char* code;\n"
            "    int32_t lat_e6;\n"
            "    int32_t lng_e6;\n"
            "    const char* routes;   // comma-separated route ids\n"
            "    const char* nameEn;   // English name (UTF-8)\n"
            "    const char* nameCn;   // Chinese name (UTF-8)\n"
            "};\n\n"
            "constexpr Stop kStops[] = {\n")
        for s in stops:
            en = s.get("nameEn", "") or s.get("nameCn", "")
            cn = s.get("nameCn", "") or s.get("nameEn", "")
            en = en.replace("\\", "\\\\").replace('"', '\\"')
            cn = cn.replace("\\", "\\\\").replace('"', '\\"')
            f.write('    {"%s", %d, %d, "%s", "%s", "%s"},\n' % (
                s["id"], int(s["lat"] * 1e6), int(s["lng"] * 1e6),
                ",".join(s.get("route_ids", [])), en, cn))
        f.write("};\n\nconstexpr int kStopCount =\n"
                "    sizeof(kStops) / sizeof(kStops[0]);\n\n"
                "}  // namespace bus_stops\n")
    print(f"stops: {len(stops)} entries written")


if __name__ == "__main__":
    sys.exit(main())
